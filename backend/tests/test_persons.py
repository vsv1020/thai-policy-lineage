def test_redact_before_model():
    text = "เรียน รอง นรม. (นายเอกนิติ นิติทัณฑ์ประภาศ) และ รมว.พณ. (นางศุภจี สุธรรมพันธุ์) เรื่อง นายจ้างต้องแจ้ง"
    out, n = redact(text)
    assert n == 2 and "เอกนิติ" not in out and "ศุภจี" not in out
    assert "นายจ้าง" in out and "[人名略]" in out


