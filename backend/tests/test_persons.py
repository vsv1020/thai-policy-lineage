        "ประกาศศาลเยาวชนและครอบครัวจังหวัดพัทลุง เรื่อง ศาลมีคำสั่งให้เป็นคนไร้ความสามารถ [ร.ต.ต. วิน  นุรัตน์]",
        "ประกาศเจ้าพนักงานพิทักษ์ทรัพย์ เรื่อง ปลดลูกหนี้จากล้มละลาย [คดีหมายเลขแดงที่ ล.4553/2565  ด.ต.หรือ จ.ส.ต.ประมวล]",
