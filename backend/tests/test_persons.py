def test_individual_notices_are_blocked():
    for t in (
        "ประกาศเจ้าพนักงานพิทักษ์ทรัพย์ เรื่อง คําพิพากษาให้ลูกหนี้ล้มละลาย [คดีหมายเลขแดงที่ ล.4325/2568 สิบเอกวีรศักดิ์ สาตรอด]",
        "ประกาศศาลเยาวชนและครอบครัวกลาง เรื่อง ศาลมีคำสั่งให้ พลโทกนกรส หงส์ทอง เป็นคนไร้ความสามารถ",
        "ประกาศศาลเยาวชนและครอบครัวจังหวัดพัทลุง เรื่อง ศาลมีคำสั่งให้เป็นคนไร้ความสามารถ [ร.ต.ต. วิน  นุรัตน์]",
        "ประกาศเจ้าพนักงานพิทักษ์ทรัพย์ เรื่อง ปลดลูกหนี้จากล้มละลาย [คดีหมายเลขแดงที่ ล.4553/2565  ด.ต.หรือ จ.ส.ต.ประมวล]",
        "ประกาศ เรื่อง แต่งตั้งนายสมชาย ใจดี เป็นกรรมการ",
    ):
        assert title_person_reason(t), t
        ok, why = C.passes_red_lines(t)
        assert not ok and why.startswith("指向个人")


def test_policy_titles_pass():
    for t in (
        "กฎ ก.พ.อ. การได้รับเงินประจำตำแหน่งของข้าราชการพลเรือนในสถาบันอุดมศึกษา (ฉบับที่ 3) พ.ศ. 2569",
        "ประกาศกรมสวัสดิการและคุ้มครองแรงงาน เรื่อง หน้าที่ของนายจ้างในการจ่ายค่าจ้าง",
        "ระเบียบสำนักนายกรัฐมนตรี ว่าด้วยการบริหารงานภาครัฐ พ.ศ. ๒๕๖๙",
        "ประกาศนายทะเบียนประกันภัย เรื่อง แบบและข้อความของกรมธรรม์",
        "พ.ร.บ.การท่องเที่ยว พ.ศ. ๒๕๖๙",
        # 破产对象是公司:与人名无关,照常收录
        "ประกาศเจ้าพนักงานพิทักษ์ทรัพย์ เรื่อง คำสั่งพิทักษ์ทรัพย์เด็ดขาด [คดีหมายเลขแดงที่ ล.889/2569 บริษัทเออีซี แอนด์ อันดามัน จำกัด]",
    ):
        assert title_person_reason(t) is None, t


def test_redact_before_model():
    text = "เรียน รอง นรม. (นายเอกนิติ นิติทัณฑ์ประภาศ) และ รมว.พณ. (นางศุภจี สุธรรมพันธุ์) เรื่อง นายจ้างต้องแจ้ง"
    out, n = redact(text)
    assert n == 2 and "เอกนิติ" not in out and "ศุภจี" not in out
    assert "นายจ้าง" in out and "[人名略]" in out


