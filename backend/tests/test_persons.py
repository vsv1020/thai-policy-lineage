        "ประกาศเจ้าพนักงานพิทักษ์ทรัพย์ เรื่อง คําพิพากษาให้ลูกหนี้ล้มละลาย [คดีหมายเลขแดงที่ ล.4325/2568 สิบเอกวีรศักดิ์ สาตรอด]",
