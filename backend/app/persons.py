# -*- coding: utf-8 -*-
"""红线二:不建人名索引 —— 采集、翻译、清理共用的自然人识别规则。

三处用法:
- 采集(collect.passes_red_lines):标题指向具体个人的公告(破产、无行为能力宣告、个案判决,
  或标题里出现「นาย/นาง/นางสาว」及军警衔 + 姓名)整条不收。
- 翻译(enrich):正文送模型之前把自然人姓名替换成「[人名略]」,模型看不到就写不出;
  模型输出里如仍出现泰文称谓 + 姓名或「先生/女士」,这条输出作废。
- 清理(collect --purge-red-lines):规则收紧后,把事实层里早先收进来、现在不合规的条目删掉。

只按字面规则判断,宁可多拦:漏掉一条普通公告的代价,远小于在公开仓库里留下一个人的破产记录。
"""
from __future__ import annotations

import re

# 军警衔(全称)。只在标题里出现时才拦 —— 政策文件的标题不会以军衔开头讲制度
_RANK_WORDS = (
    "จ่าสิบตำรวจ", "จ่าสิบเอก", "จ่าสิบโท", "จ่าสิบตรี", "จ่าอากาศเอก", "จ่าอากาศโท", "จ่าอากาศตรี",
    "จ่าเอก", "จ่าโท", "จ่าตรี", "พันจ่าอากาศ", "พันจ่า",
    "สิบตำรวจเอก", "สิบตำรวจโท", "สิบตำรวจตรี", "สิบเอก", "สิบโท", "สิบตรี",
    "ดาบตำรวจ", "พลตำรวจเอก", "พลตำรวจโท", "พลตำรวจตรี",
    "ร้อยตำรวจเอก", "ร้อยตำรวจโท", "ร้อยตำรวจตรี", "ร้อยเอก", "ร้อยโท", "ร้อยตรี",
    "พันตำรวจเอก", "พันตำรวจโท", "พันตำรวจตรี", "พันเอก", "พันโท", "พันตรี",
    "พลเอก", "พลโท", "พลตรี", "พลเรือเอก", "พลเรือโท", "พลเรือตรี",
    "พลอากาศเอก", "พลอากาศโท", "พลอากาศตรี",
    "นาวาอากาศเอก", "นาวาอากาศโท", "นาวาอากาศตรี", "นาวาเอก", "นาวาโท", "นาวาตรี",
    "เรืออากาศเอก", "เรืออากาศโท", "เรืออากาศตรี", "เรือเอก", "เรือโท", "เรือตรี",
    "ว่าที่ร้อยตรี", "ว่าที่ร้อยโท", "ว่าที่เรือตรี", "หม่อมหลวง", "หม่อมราชวงศ์",
)
# 缩写衔:ด.ต. จ.ส.ต. ร.ต.อ. พ.ต.ท. พล.ต.อ. ……(不含 พ.ร.บ./พ.ศ. 这类非人名缩写)
# 前面紧贴字母或点时是机构缩写的一部分(ก.พ.อ. 高校人事委员会),不是军衔
_RANK_ABBR = r"(?<![\u0E01-\u0E4E.])(?:พล\.[ตรอ]\.[อทต]\.|พล\.[อทต]\.|[พร]\.[ตอ]\.[อทต]\.|[พร]\.[อทต]\.|จ\.ส\.[ตอท]\.|ส\.[ตอท]\.[อทต]\.|ด\.ต\.)"
RANK = "(?:" + "|".join(sorted(map(re.escape, _RANK_WORDS), key=len, reverse=True)) + "|" + _RANK_ABBR + ")"

# 平民称谓。นาย 开头的职务词(นายกรัฐมนตรี 总理、นายจ้าง 雇主、นายทะเบียน 登记官……)不是人名
_NAI_NOT_NAME = (r"ก(?:รัฐมนตรี|เทศมนตรี|องค์การ|สมาคม|สภา|ฯ|\s)|จ้าง|ทะเบียน|หน้า|อำเภอ|ตรวจ|ช่าง|ประกัน|"
                 r"ท่า|เรือ|ทหาร|สถานี|ด่าน|ร้อย|สิบ|พล|พัน|ดาบ|เวร|งาน|ห้าง|ทุน|ประตู|บ่อน")
_NANG_NOT_NAME = r"พยาบาล|งาม|ฟ้า"
CIVIL = (rf"(?:นางสาว|นาง(?!{_NANG_NOT_NAME})|นาย(?!{_NAI_NOT_NAME})|ดร\.|นพ\.|พญ\.|ทพ\.|ทพญ\.|"
         rf"นายแพทย์|แพทย์หญิง)")
_THAI_WORD = r"[ก-๎]+"            # 泰文字母与元音,不含泰文数字
# 称谓 + 名 (+ 姓):名常紧贴称谓,姓与名之间有空格
NAME = re.compile(rf"(?:{RANK}|{CIVIL})(?:หญิง)?\s?{_THAI_WORD}(?:\s+{_THAI_WORD})?")

# 指向具体个人的公告类型(标题字面即可判断)
_INDIVIDUAL_NOTICE = (
    ("เจ้าพนักงานพิทักษ์ทรัพย์", "破产个案公告"),
    ("ไร้ความสามารถ", "无行为能力宣告"),
    ("คดีหมายเลขแดง", "个案判决"),
    ("คดีหมายเลขดำ", "个案判决"),
)

# 译文里的称谓:中文称呼与残留的泰文称谓
_ZH_HONORIFIC = re.compile(r"先生|女士|小姐")
PLACEHOLDER = "[人名略]"


# 破产、判决的对象是公司(保险公司破产等)时与人名无关,照常收录 —— 前提是标题里没有自然人姓名
_COMPANY = ("บริษัท", "ห้างหุ้นส่วน")


def title_person_reason(title: str) -> str | None:
    """标题指向具体个人时返回原因,否则 None。"""
    title = title or ""
    if NAME.search(title):
        return "含自然人姓名"
    for marker, why in _INDIVIDUAL_NOTICE:
        if marker in title and not any(c in title for c in _COMPANY):
            return why
    return None


def redact(text: str) -> tuple[str, int]:
    """把正文里的自然人姓名换成占位符。返回 (新文本, 替换次数)。"""
    return NAME.subn(PLACEHOLDER, text or "")


def output_person_reason(text: str) -> str | None:
    """模型输出里出现人名痕迹时返回原因。中文音译姓名无法可靠识别,靠送模型前的 redact 兜住。"""
    if NAME.search(text or ""):
        return "泰文称谓+姓名"
    if _ZH_HONORIFIC.search(text or ""):
        return "中文称谓"
    return None
